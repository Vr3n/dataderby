CREATE TABLE IF NOT EXISTS pipeline_checkpoint (
    whoscored_tournament_id  INTEGER NOT NULL CHECK (whoscored_tournament_id > 0),
    whoscored_season_id      INTEGER NOT NULL CHECK (whoscored_season_id > 0),
    whoscored_stage_id       INTEGER NOT NULL CHECK (whoscored_stage_id > 0),
    last_accepted_snapshot_id VARCHAR,
    last_committed_fingerprint VARCHAR,
    last_probe_at            TIMESTAMP WITH TIME ZONE,
    last_success_at          TIMESTAMP WITH TIME ZONE,
    last_outcome             VARCHAR,
    attempt_count            INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    abandoned_runs           INTEGER NOT NULL DEFAULT 0 CHECK (abandoned_runs >= 0),
    PRIMARY KEY (whoscored_tournament_id, whoscored_season_id, whoscored_stage_id)
