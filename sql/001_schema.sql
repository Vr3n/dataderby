-- v1 schema. Every table is append-only; no delete path is part of v1.
-- Source-derived identifiers carry the source name; measurements do not.

CREATE TABLE IF NOT EXISTS ingestion_run (
    run_id                    VARCHAR PRIMARY KEY,
    mode                      VARCHAR NOT NULL,
    started_at                TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at               TIMESTAMP WITH TIME ZONE,
    outcome                   VARCHAR NOT NULL DEFAULT 'running',
    whoscored_tournament_id   INTEGER NOT NULL CHECK (whoscored_tournament_id > 0),
    whoscored_season_id       INTEGER NOT NULL CHECK (whoscored_season_id > 0),
    whoscored_stage_id        INTEGER NOT NULL CHECK (whoscored_stage_id > 0),
    observed_at               TIMESTAMP WITH TIME ZONE,
    accepted_snapshot_id      VARCHAR,
    http_requests             INTEGER NOT NULL DEFAULT 0 CHECK (http_requests >= 0),
    error_code                VARCHAR,
    error_detail              VARCHAR,
    CHECK (outcome IN ('running', 'accepted', 'no_change', 'fetch_failed',
                       'blocked', 'abandoned', 'crashed'))
);

CREATE TABLE IF NOT EXISTS raw_capture (
    run_id        VARCHAR NOT NULL,
    section       VARCHAR NOT NULL,
    view          VARCHAR NOT NULL,
    attempt       INTEGER NOT NULL CHECK (attempt > 0),
    captured_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    path          VARCHAR NOT NULL,
    byte_count    INTEGER NOT NULL CHECK (byte_count >= 0),
    sha256        VARCHAR NOT NULL,
    content_type  VARCHAR,
    is_gate       BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (run_id, section, view)
);

CREATE TABLE IF NOT EXISTS competition_snapshot (
    snapshot_id              VARCHAR PRIMARY KEY,
    parent_snapshot_id       VARCHAR NOT NULL DEFAULT 'genesis',
    whoscored_tournament_id  INTEGER NOT NULL CHECK (whoscored_tournament_id > 0),
    whoscored_season_id      INTEGER NOT NULL CHECK (whoscored_season_id > 0),
    whoscored_stage_id       INTEGER NOT NULL CHECK (whoscored_stage_id > 0),
    season_key               VARCHAR NOT NULL,
    content_fingerprint      VARCHAR NOT NULL,
    canonical_version        INTEGER NOT NULL CHECK (canonical_version > 0),
    observed_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    accepted_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    capture_span_seconds     DOUBLE NOT NULL CHECK (capture_span_seconds >= 0),
    is_opta                  BOOLEAN NOT NULL,
    whoscored_page_url       VARCHAR NOT NULL,
    run_id                   VARCHAR NOT NULL,
    UNIQUE (parent_snapshot_id, content_fingerprint),
    UNIQUE (whoscored_tournament_id, whoscored_season_id, whoscored_stage_id, observed_at)
);

